/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_I2C1_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  ssd1306_Init();
  uint8_t current_state_screen = 0;
  uint8_t button_last_state = 1;
  uint32_t last_activity = 0;
  uint8_t display_on = 1;
  uint8_t near_count = 0;
  sr04.trig_port = GPIOA;
  sr04.trig_pin = GPIO_PIN_9;
  sr04.echo_htim = &htim3;
  sr04.echo_channel = TIM_CHANNEL_1;
  sr04_init(&sr04);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	      // 1. Опрос кнопки
	  uint8_t button_current_state = HAL_GPIO_ReadPin(GPIOC, GPIO_PIN_13);
	  if(button_current_state == GPIO_PIN_RESET && button_last_state == 1)
	  {
	      current_state_screen += 1;
	      if(current_state_screen > 2)
	          current_state_screen = 0;
	      last_activity = HAL_GetTick();
	  }
	  button_last_state = button_current_state;

	  // Логика близости
	  if(sr04.distance < 500)
	  {
	      near_count++;
	      if(near_count > 3) near_count = 3;
	  }
	  else
	  {
	      if(near_count > 0) near_count--;
	  }
	  if(near_count >= 3)
	  {
	      last_activity = HAL_GetTick();
	  }

	  // Таймаут экрана
	  if(HAL_GetTick() - last_activity > 10000)
	  {
	      if(display_on)
	      {
	          ssd1306_SetDisplayOn(0);
	          display_on = 0;
	      }
	  }
	  else
	  {
	      if(!display_on)
	      {
	          ssd1306_SetDisplayOn(1);
	          display_on = 1;
	      }
	  }

	  char buf[32];
	  ssd1306_Fill(0);
	  switch(current_state_screen)
	  {
	      case 0:
	          ssd1306_SetCursor(0, 0);
	          ssd1306_WriteString("Temp:", Font_11x18, 1);
	          sprintf(buf, "-- C");
	          ssd1306_SetCursor(0, 20);
	          ssd1306_WriteString(buf, Font_11x18, 1);
	          break;
	      case 1:
	          ssd1306_SetCursor(0, 0);
	          ssd1306_WriteString("Hum:", Font_11x18, 1);
	          sprintf(buf, "-- %%");
	          ssd1306_SetCursor(0, 20);
	          ssd1306_WriteString(buf, Font_11x18, 1);
	          break;
	      case 2:
	          ssd1306_SetCursor(0, 0);
	          ssd1306_WriteString("Dist:", Font_11x18, 1);
	          sprintf(buf, "%lu mm", sr04.distance);
	          ssd1306_SetCursor(0, 20);
	          ssd1306_WriteString(buf, Font_11x18, 1);
	          break;
	  }
	  sr04_trigger(&sr04);
	  ssd1306_UpdateScreen();
	  HAL_Delay(100);

    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

